function extractDomain(urlOrName: string): string | null {
  const clean = (urlOrName || "").trim().toLowerCase();
  if (!clean) return null;

  // Direct brand lookup
  const simpleMatch = clean.replace(/[^a-z0-9]/g, "");
  if (BRAND_LOGOS[simpleMatch]) return `${simpleMatch}.com`;

  // Try URL parsing
  try {
    const formatted = clean.startsWith("http://") || clean.startsWith("https://")
      ? clean
      : `https://${clean}`;
    const parsed = new URL(formatted);
    const host = parsed.hostname.replace(/^www\./, "");
    if (host.includes(".")) return host;
  } catch {
    // If not a full URL, check if provider has a dot (e.g. github.com)
    if (clean.includes(".") && !clean.includes(" ")) {
      return clean.replace(/^www\./, "");
    }
  }

  // Common platform heuristic lookup
  const COMMON_DOMAINS: Record<string, string> = {
    facebook: "facebook.com",
    fb: "facebook.com",
    netflix: "netflix.com",
    google: "google.com",
    gmail: "google.com",
    github: "github.com",
    apple: "apple.com",
    icloud: "apple.com",
    microsoft: "microsoft.com",
    outlook: "microsoft.com",
    amazon: "amazon.com",
    aws: "amazon.com",
    spotify: "spotify.com",
    discord: "discord.com",
    twitter: "x.com",
    x: "x.com",
    instagram: "instagram.com",
    linkedin: "linkedin.com",
    youtube: "youtube.com",
    reddit: "reddit.com",
    twitch: "twitch.tv",
    tiktok: "tiktok.com",
    paypal: "paypal.com",
    notion: "notion.so",
    slack: "slack.com",
    figma: "figma.com",
    dropbox: "dropbox.com",
    openai: "openai.com",
    chatgpt: "openai.com",
    steam: "steampowered.com",
    roblox: "roblox.com",
    gitlab: "gitlab.com",
    zoom: "zoom.us",
  };

  for (const [key, domain] of Object.entries(COMMON_DOMAINS)) {
    if (clean.includes(key)) return domain;
  }

  return null;
}

function providerInitial(name: string) {
  return (name.trim()[0] || "?").toUpperCase();
}

function avatarGradient(name: string) {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) % 360;
  const h2 = (h + 40) % 360;
  return `linear-gradient(135deg, hsl(${h} 75% 55%), hsl(${h2} 80% 45%))`;
}

